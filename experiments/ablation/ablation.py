#!/usr/bin/env python3
"""
Ablation study analysis: compare HK2017 algorithm variants.

Phase A: V0 (unpruned) vs V1 (pruned) baselines.
Phase B: V4 (directed Reeb adjacency) and V5 (SVD-only solver).

Input: experiments/ablation/ablation.jsonl (generated by ablation.rs)
Output: experiments/ablation/ablation_timing.png (timing comparison figure)
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

EXPERIMENT_DIR = Path(__file__).resolve().parent
DATA_PATH = EXPERIMENT_DIR / "ablation.jsonl"
FIGURE_PATH = EXPERIMENT_DIR / "ablation_timing.png"

VARIANTS = ["v0_unpruned", "v1_pruned", "v4_directed", "v5_svd_only"]
VARIANT_LABELS = {
    "v0_unpruned": "V0 unpruned",
    "v1_pruned": "V1 pruned",
    "v4_directed": "V4 directed",
    "v5_svd_only": "V5 SVD-only",
}
GROUPS = ["random_generic", "random_lagrangian", "regression"]


# ============================================================================
# Data loading
# ============================================================================

def load_dataset():
    """Load ablation JSONL. Returns list of entry dicts."""
    if not DATA_PATH.exists():
        print(f"Dataset not found: {DATA_PATH}", file=sys.stderr)
        print(
            "Run: cd experiments && cargo run --bin ablation --release",
            file=sys.stderr,
        )
        sys.exit(1)

    entries = []
    with open(DATA_PATH) as f:
        for line in f:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


# ============================================================================
# Agreement check
# ============================================================================

def check_agreement(entries):
    """
    Check that all variants agree on capacity.
    Returns (n_disagreements, disagreement_list).
    """
    by_polytope = defaultdict(dict)
    for e in entries:
        by_polytope[e["polytope_name"]][e["variant"]] = e

    disagreements = []
    for name, variants in sorted(by_polytope.items()):
        if len(variants) < 2:
            continue
        caps = {v: d["capacity"] for v, d in variants.items()}
        values = list(caps.values())
        max_diff = max(abs(a - b) for a in values for b in values)
        if max_diff > 1e-5:
            disagreements.append({
                "polytope": name,
                "group": next(iter(variants.values()))["group"],
                "facets": next(iter(variants.values()))["facet_count"],
                **caps,
                "max_diff": max_diff,
            })

    return len(disagreements), disagreements


# ============================================================================
# Summary tables
# ============================================================================

def print_agreement_table(entries):
    """Print per-polytope capacity agreement across all variants."""
    by_polytope = defaultdict(dict)
    for e in entries:
        by_polytope[e["polytope_name"]][e["variant"]] = e

    active_variants = sorted(set(e["variant"] for e in entries))
    hdr_caps = " ".join(f"{VARIANT_LABELS.get(v, v):>12}" for v in active_variants)
    print(f"\n=== Capacity Agreement: all variants ===")
    print(f"{'Polytope':<35} {'F':>3} {hdr_caps} {'max|diff|':>10} {'Status'}")
    print("-" * (55 + 13 * len(active_variants)))

    n_ok = 0
    n_fail = 0
    for name in sorted(by_polytope.keys()):
        variants = by_polytope[name]
        f = next(iter(variants.values()))["facet_count"]

        caps = [variants.get(v, {}).get("capacity", float("nan")) for v in active_variants]
        diff = max(abs(a - b) for a in caps for b in caps)
        status = "OK" if diff < 1e-5 else "DISAGREE"
        if diff < 1e-5:
            n_ok += 1
        else:
            n_fail += 1

        cap_str = " ".join(f"{c:>12.8f}" for c in caps)
        flag = " *" if diff >= 1e-5 else ""
        print(f"{name:<35} {f:>3} {cap_str} {diff:>10.2e} {status}{flag}")

    print("-" * (55 + 13 * len(active_variants)))
    print(f"Agreement: {n_ok}/{n_ok + n_fail} polytopes OK")
    if n_fail > 0:
        print(f"DISAGREEMENTS: {n_fail} polytopes differ by > 1e-5")
    return n_fail


def print_timing_table(entries):
    """Print timing comparison table per group and F, all variants."""
    by_group_f_variant = defaultdict(list)
    for e in entries:
        if e["group"] == "regression":
            continue
        key = (e["group"], e["facet_count"], e["variant"])
        by_group_f_variant[key].append(e["time_ms"])

    group_f_pairs = sorted(set(
        (g, f) for (g, f, _v) in by_group_f_variant
    ))

    active_variants = [v for v in VARIANTS if any(
        (g, f, v) in by_group_f_variant for g, f in group_f_pairs
    )]

    print(f"\n=== Timing Comparison: all variants ===")
    hdr = f"{'Group':<20} {'F':>3}"
    for v in active_variants:
        hdr += f" {VARIANT_LABELS.get(v, v) + ' (ms)':>14}"
    hdr += f" {'V1/V0':>7} {'V4/V0':>7} {'N':>4}"
    print(hdr)
    print("-" * len(hdr))

    for group, f in group_f_pairs:
        means = {}
        row = f"{group:<20} {f:>3}"
        for v in active_variants:
            times = by_group_f_variant.get((group, f, v), [])
            if times:
                m = float(np.mean(times))
                means[v] = m
                row += f" {m:>14.1f}"
            else:
                row += f" {'--':>14}"

        # Speedup ratios relative to V0
        m0 = means.get("v0_unpruned")
        m1 = means.get("v1_pruned")
        m4 = means.get("v4_directed")
        ratio_v1 = f"{m0/m1:.1f}x" if m0 and m1 else "--"
        ratio_v4 = f"{m0/m4:.1f}x" if m0 and m4 else "--"
        n = len(by_group_f_variant.get((group, f, active_variants[0]), []))
        row += f" {ratio_v1:>7} {ratio_v4:>7} {n:>4}"
        print(row)

    print()


def print_iteration_table(entries):
    """Print iteration count comparison (measures pruning effectiveness)."""
    by_group_f_variant = defaultdict(list)
    for e in entries:
        if e["group"] == "regression":
            continue
        key = (e["group"], e["facet_count"], e["variant"])
        by_group_f_variant[key].append(e["iterations"])

    group_f_pairs = sorted(set(
        (g, f) for (g, f, _v) in by_group_f_variant
    ))

    active_variants = [v for v in VARIANTS if any(
        (g, f, v) in by_group_f_variant for g, f in group_f_pairs
    )]

    print(f"\n=== Iteration Counts: pruning effectiveness ===")
    hdr = f"{'Group':<20} {'F':>3}"
    for v in active_variants:
        hdr += f" {VARIANT_LABELS.get(v, v):>12}"
    hdr += f" {'V1/V0':>8} {'V4/V0':>8}"
    print(hdr)
    print("-" * len(hdr))

    for group, f in group_f_pairs:
        means = {}
        row = f"{group:<20} {f:>3}"
        for v in active_variants:
            iters = by_group_f_variant.get((group, f, v), [])
            if iters:
                m = float(np.mean(iters))
                means[v] = m
                row += f" {m:>12.0f}"
            else:
                row += f" {'--':>12}"

        m0 = means.get("v0_unpruned")
        m1 = means.get("v1_pruned")
        m4 = means.get("v4_directed")
        r1 = f"{m1/m0:.3f}" if m0 and m1 else "--"
        r4 = f"{m4/m0:.3f}" if m0 and m4 else "--"
        row += f" {r1:>8} {r4:>8}"
        print(row)

    print()


def print_regression_table(entries):
    """Print regression cases: capacity vs expected."""
    regression = [e for e in entries if e["group"] == "regression"]
    if not regression:
        return

    print("=== Regression Cases ===")
    print(f"{'Polytope':<35} {'Variant':<15} {'Capacity':>12} {'Time (ms)':>10} {'Iters':>10}")
    print("-" * 85)

    for e in sorted(regression, key=lambda x: (x["polytope_name"], x["variant"])):
        print(
            f"{e['polytope_name']:<35} {e['variant']:<15} {e['capacity']:>12.8f} "
            f"{e['time_ms']:>10.2f} {e['iterations']:>10}"
        )
    print()


# ============================================================================
# Figure
# ============================================================================

def plot_timing(entries):
    """Timing comparison figure: all variants per group and F."""
    groups_to_plot = ["random_generic", "random_lagrangian"]
    group_display = {
        "random_generic": "Random generic polytopes",
        "random_lagrangian": "Random Lagrangian products",
    }

    fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharey=False)

    colors = {
        "v0_unpruned": "#e08020",
        "v1_pruned": "#2060c0",
        "v4_directed": "#20a040",
        "v5_svd_only": "#a02080",
    }
    markers = {
        "v0_unpruned": "^",
        "v1_pruned": "o",
        "v4_directed": "s",
        "v5_svd_only": "D",
    }

    for ax, group in zip(axes, groups_to_plot):
        group_entries = [e for e in entries if e["group"] == group]

        by_variant_f = defaultdict(lambda: defaultdict(list))
        for e in group_entries:
            by_variant_f[e["variant"]][e["facet_count"]].append(e["time_ms"])

        for variant in VARIANTS:
            f_vals = sorted(by_variant_f[variant].keys())
            if not f_vals:
                continue

            means = [float(np.mean(by_variant_f[variant][f])) for f in f_vals]
            stds = [float(np.std(by_variant_f[variant][f], ddof=1)) for f in f_vals]

            ax.errorbar(
                f_vals,
                means,
                yerr=stds,
                marker=markers[variant],
                color=colors[variant],
                linewidth=2,
                markersize=6,
                capsize=4,
                capthick=1.5,
                elinewidth=1.5,
                alpha=0.9,
                label=f"{VARIANT_LABELS[variant]}",
            )

        ax.set_yscale("log")
        ax.set_xlabel("Facet count $F$", fontsize=11)
        ax.set_ylabel("Time (ms)", fontsize=11)
        ax.set_title(group_display[group], fontsize=11)
        ax.legend(fontsize=9)
        ax.grid(True, alpha=0.3, which="both")

    fig.suptitle(
        "Algorithm variant timing by facet count (mean $\\pm$ std, $n=5$)",
        fontsize=12,
    )
    fig.tight_layout()
    fig.savefig(FIGURE_PATH, dpi=150)
    plt.close(fig)
    print(f"Figure: {FIGURE_PATH}")


# ============================================================================
# Main
# ============================================================================

def main():
    entries = load_dataset()
    n_total = len(entries)
    n_polytopes = len(set(e["polytope_name"] for e in entries))
    n_variants = len(set(e["variant"] for e in entries))
    print(f"Loaded {n_total} entries ({n_polytopes} polytopes x {n_variants} variants)")
    print(f"Groups: {sorted(set(e['group'] for e in entries))}")

    print_regression_table(entries)
    n_disagree = print_agreement_table(entries)
    print_timing_table(entries)
    print_iteration_table(entries)
    plot_timing(entries)

    if n_disagree > 0:
        print(f"\nFAILURE: {n_disagree} disagreements found.", file=sys.stderr)
        sys.exit(1)
    else:
        print("\nAll variants agree. Ablation study complete.")


if __name__ == "__main__":
    main()
