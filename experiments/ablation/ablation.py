#!/usr/bin/env python3
"""
Ablation study analysis: compare HK2017 algorithm variants.

Goal: Verify V0 (unpruned) and V1 (pruned) agree on all test polytopes,
      measure pruning speedup across facet counts and polytope groups.
Input: experiments/ablation/ablation.jsonl (generated by ablation.rs)
Output: experiments/ablation/ablation_timing.png (timing comparison figure)
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

EXPERIMENT_DIR = Path(__file__).resolve().parent
DATA_PATH = EXPERIMENT_DIR / "ablation.jsonl"
FIGURE_PATH = EXPERIMENT_DIR / "ablation_timing.png"

VARIANTS = ["v0_unpruned", "v1_pruned"]
VARIANT_LABELS = {
    "v0_unpruned": "V0 unpruned",
    "v1_pruned":   "V1 pruned",
}
GROUPS = ["random_generic", "random_lagrangian", "regression"]


# ============================================================================
# Data loading
# ============================================================================

def load_dataset():
    """Load ablation JSONL. Returns list of entry dicts."""
    if not DATA_PATH.exists():
        print(f"Dataset not found: {DATA_PATH}", file=sys.stderr)
        print(
            "Run: cd experiments && cargo run --bin ablation --release",
            file=sys.stderr,
        )
        sys.exit(1)

    entries = []
    with open(DATA_PATH) as f:
        for line in f:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


# ============================================================================
# Agreement check
# ============================================================================

def check_agreement(entries):
    """
    Check that all variants agree on capacity.
    Returns (n_disagreements, disagreement_list).
    """
    # Group by polytope name
    by_polytope = defaultdict(dict)
    for e in entries:
        by_polytope[e["polytope_name"]][e["variant"]] = e

    disagreements = []
    for name, variants in sorted(by_polytope.items()):
        if len(variants) < 2:
            continue
        caps = {v: d["capacity"] for v, d in variants.items()}
        values = list(caps.values())
        max_diff = max(abs(a - b) for a in values for b in values)
        if max_diff > 1e-5:
            disagreements.append({
                "polytope": name,
                "group": next(iter(variants.values()))["group"],
                "facets": next(iter(variants.values()))["facet_count"],
                **caps,
                "max_diff": max_diff,
            })

    return len(disagreements), disagreements


# ============================================================================
# Summary tables
# ============================================================================

def print_agreement_table(entries):
    """Print per-polytope capacity agreement between V0 and V1."""
    by_polytope = defaultdict(dict)
    for e in entries:
        by_polytope[e["polytope_name"]][e["variant"]] = e

    print("\n=== Capacity Agreement: V0 (unpruned) vs V1 (pruned) ===")
    print(
        f"{'Polytope':<35} {'F':>3} {'V0':>12} {'V1':>12} {'|diff|':>10} {'Status'}"
    )
    print("-" * 80)

    n_ok = 0
    n_fail = 0
    for name in sorted(by_polytope.keys()):
        variants = by_polytope[name]
        f = next(iter(variants.values()))["facet_count"]
        group = next(iter(variants.values()))["group"]

        c0 = variants.get("v0_unpruned", {}).get("capacity", float("nan"))
        c1 = variants.get("v1_pruned", {}).get("capacity", float("nan"))
        diff = abs(c0 - c1)
        status = "OK" if diff < 1e-5 else "DISAGREE"
        if diff < 1e-5:
            n_ok += 1
        else:
            n_fail += 1

        flag = " *" if diff >= 1e-5 else ""
        print(
            f"{name:<35} {f:>3} {c0:>12.8f} {c1:>12.8f} {diff:>10.2e} {status}{flag}"
        )

    print("-" * 80)
    print(f"Agreement: {n_ok}/{n_ok + n_fail} polytopes OK")
    if n_fail > 0:
        print(f"DISAGREEMENTS: {n_fail} polytopes differ by > 1e-5")
    return n_fail


def print_timing_table(entries):
    """Print timing comparison table: V0 vs V1 per group and F."""
    # Collect (group, F, variant, time_ms) — key is a 3-tuple, value is a list
    by_group_f_variant = defaultdict(list)
    for e in entries:
        if e["group"] == "regression":
            continue  # regression cases are fixed, not meaningful for timing stats
        key = (e["group"], e["facet_count"], e["variant"])
        by_group_f_variant[key].append(e["time_ms"])

    # Get all (group, F) pairs
    group_f_pairs = set()
    for (group, f, _v) in by_group_f_variant:
        group_f_pairs.add((group, f))

    print("\n=== Timing Comparison: V0 (unpruned) vs V1 (pruned) ===")
    print(f"{'Group':<20} {'F':>3} {'V0 mean':>10} {'V0 std':>8} {'V1 mean':>10} {'V1 std':>8} {'Speedup':>8} {'N':>4}")
    print("-" * 80)

    for group, f in sorted(group_f_pairs):
        t0 = by_group_f_variant[(group, f, "v0_unpruned")]
        t1 = by_group_f_variant[(group, f, "v1_pruned")]
        n = min(len(t0), len(t1))
        if n == 0:
            continue
        mean0 = float(np.mean(t0))
        std0  = float(np.std(t0, ddof=1))
        mean1 = float(np.mean(t1))
        std1  = float(np.std(t1, ddof=1))
        speedup = mean0 / mean1 if mean1 > 0 else float("inf")
        print(
            f"{group:<20} {f:>3} {mean0:>10.1f} {std0:>8.1f} {mean1:>10.1f} {std1:>8.1f} {speedup:>7.2f}x {n:>4}"
        )

    print()


def print_regression_table(entries):
    """Print regression cases: capacity vs expected."""
    regression = [e for e in entries if e["group"] == "regression"]
    if not regression:
        return

    print("=== Regression Cases ===")
    print(f"{'Polytope':<35} {'Variant':<15} {'Capacity':>12} {'Time (ms)':>10} {'Iters':>10}")
    print("-" * 80)

    for e in sorted(regression, key=lambda x: (x["polytope_name"], x["variant"])):
        print(
            f"{e['polytope_name']:<35} {e['variant']:<15} {e['capacity']:>12.8f} "
            f"{e['time_ms']:>10.2f} {e['iterations']:>10}"
        )
    print()


# ============================================================================
# Figure
# ============================================================================

def plot_timing(entries):
    """Timing comparison figure: V0 vs V1 per group and F."""
    # Separate groups (exclude regression from timing figure)
    groups_to_plot = ["random_generic", "random_lagrangian"]
    group_display = {
        "random_generic":    "Random generic polytopes",
        "random_lagrangian": "Random Lagrangian products",
    }

    fig, axes = plt.subplots(1, 2, figsize=(12, 5), sharey=False)

    colors = {"v0_unpruned": "#e08020", "v1_pruned": "#2060c0"}
    markers = {"v0_unpruned": "^", "v1_pruned": "o"}

    for ax, group in zip(axes, groups_to_plot):
        group_entries = [e for e in entries if e["group"] == group]

        # Group by (variant, F)
        by_variant_f = defaultdict(lambda: defaultdict(list))
        for e in group_entries:
            by_variant_f[e["variant"]][e["facet_count"]].append(e["time_ms"])

        for variant in VARIANTS:
            f_vals = sorted(by_variant_f[variant].keys())
            if not f_vals:
                continue

            means = [float(np.mean(by_variant_f[variant][f])) for f in f_vals]
            stds  = [float(np.std(by_variant_f[variant][f], ddof=1)) for f in f_vals]

            ax.errorbar(
                f_vals,
                means,
                yerr=stds,
                marker=markers[variant],
                color=colors[variant],
                linewidth=2,
                markersize=6,
                capsize=4,
                capthick=1.5,
                elinewidth=1.5,
                alpha=0.9,
                label=f"{VARIANT_LABELS[variant]} (mean ± std)",
            )

        ax.set_yscale("log")
        ax.set_xlabel("Facet count $F$", fontsize=11)
        ax.set_ylabel("Time (ms)", fontsize=11)
        ax.set_title(group_display[group], fontsize=11)
        ax.legend(fontsize=9)
        ax.grid(True, alpha=0.3, which="both")

    fig.suptitle(
        "V0 (unpruned) vs V1 (pruned): timing by facet count (mean ± std, $n=5$)",
        fontsize=12,
    )
    fig.tight_layout()
    fig.savefig(FIGURE_PATH, dpi=150)
    plt.close(fig)
    print(f"Figure: {FIGURE_PATH}")


# ============================================================================
# Main
# ============================================================================

def main():
    entries = load_dataset()
    n_total = len(entries)
    n_polytopes = len(set(e["polytope_name"] for e in entries))
    n_variants = len(set(e["variant"] for e in entries))
    print(f"Loaded {n_total} entries ({n_polytopes} polytopes × {n_variants} variants)")
    print(f"Groups: {sorted(set(e['group'] for e in entries))}")

    print_regression_table(entries)
    n_disagree = print_agreement_table(entries)
    print_timing_table(entries)
    plot_timing(entries)

    if n_disagree > 0:
        print(f"\nFAILURE: {n_disagree} disagreements found.", file=sys.stderr)
        sys.exit(1)
    else:
        print("All variants agree. Phase A baseline complete.")


if __name__ == "__main__":
    main()
