#!/usr/bin/env python3
"""
Ablation study analysis: compare HK2017 adjacency graph pruning variants (A-axis).

A0 (unpruned) → A1 (vertex adjacency) → A2 (directed ω₀) → A3 (Reeb-flow feasibility).
Each variant adds strictly more pruning than the previous.

Input: crates/dev-algorithm-comparison/ablation/ablation.jsonl (generated by ablation.rs)
Output: crates/dev-algorithm-comparison/ablation/ablation_timing.png (timing comparison figure)
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from figure_config import setup, TEXT_WIDTH
setup()

EXPERIMENT_DIR = Path(__file__).resolve().parent
DATA_PATH = EXPERIMENT_DIR / "ablation.jsonl"
FIGURE_PATH = EXPERIMENT_DIR / "ablation_timing.png"

VARIANTS = ["a0_unpruned", "a1_vertex_adj", "a2_omega_directed", "a3_reeb_feasible"]
VARIANT_LABELS = {
    "a0_unpruned": "A0 unpruned",
    "a1_vertex_adj": "A1 vertex adj",
    "a2_omega_directed": "A2 directed ω₀",
    "a3_reeb_feasible": "A3 Reeb feasible",
}
GROUPS = ["random_generic", "random_lagrangian", "regression", "non_simple"]


# ============================================================================
# Data loading
# ============================================================================

def load_dataset():
    """Load ablation JSONL. Returns list of entry dicts."""
    if not DATA_PATH.exists():
        print(f"Dataset not found: {DATA_PATH}", file=sys.stderr)
        print(
            "Run: cd experiments && cargo run --bin ablation --release",
            file=sys.stderr,
        )
        sys.exit(1)

    entries = []
    with open(DATA_PATH) as f:
        for line in f:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


# ============================================================================
# Agreement check
# ============================================================================

def check_agreement(entries):
    """
    Check that all variants agree on capacity.
    Returns (n_disagreements, disagreement_list).
    """
    by_polytope = defaultdict(dict)
    for e in entries:
        by_polytope[e["polytope_name"]][e["variant"]] = e

    disagreements = []
    for name, variants in sorted(by_polytope.items()):
        if len(variants) < 2:
            continue
        caps = {v: d["capacity"] for v, d in variants.items()}
        values = list(caps.values())
        max_diff = max(abs(a - b) for a in values for b in values)
        if max_diff > 1e-5:
            disagreements.append({
                "polytope": name,
                "group": next(iter(variants.values()))["group"],
                "facets": next(iter(variants.values()))["facet_count"],
                **caps,
                "max_diff": max_diff,
            })

    return len(disagreements), disagreements


