#!/usr/bin/env python3
"""
Benchmark EHZ capacity computation across facet counts.

Goal: Derive timing model T(F) = a * b^F from benchmark dataset,
      produce one figure showing both polytope classes.
Input: crates/exp-algorithm-comparison/benchmark/benchmark.jsonl (generated by benchmark.rs)
Output: crates/exp-algorithm-comparison/benchmark/profiling/timing_model.json (updated model),
        crates/exp-algorithm-comparison/benchmark/benchmark_timing.png (unified figure)
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from figure_config import setup, TEXT_WIDTH
setup()

EXPERIMENT_DIR = Path(__file__).resolve().parent
PROFILING_DIR = EXPERIMENT_DIR / "profiling"
FIGURES_DIR = EXPERIMENT_DIR
DATA_PATH = EXPERIMENT_DIR / "benchmark.jsonl"

MODEL_PATH = PROFILING_DIR / "timing_model.json"


def load_dataset():
    """Load benchmark dataset JSONL with all three algorithms."""
    pruned_rows = []
    unpruned_rows = []
    billiard_rows = []

    with open(DATA_PATH) as f:
        for line in f:
            row = json.loads(line)

            # Pruned (all polytopes)
            pruned_rows.append({
                "facets": row["facet_count"],
                "time_ms": row["time_pruned_ms"],
                "capacity": row["capacity_pruned"],
                "iterations": row["iterations_pruned"],
                "group": row["group"],
            })

            # Unpruned (F≤7 only, random polytopes only)
            if row["time_unpruned_ms"] is not None:
                unpruned_rows.append({
                    "facets": row["facet_count"],
                    "time_ms": row["time_unpruned_ms"],
                    "capacity": row["capacity_unpruned"],
                    "iterations": row["iterations_unpruned"],
                })

            # Billiard (Lagrangian products only)
            if row["time_billiard_ms"] is not None:
                billiard_rows.append({
                    "facets": row["facet_count"],
                    "time_ms": row["time_billiard_ms"],
                    "capacity": row["capacity_billiard"],
                    "iterations": row["iterations_billiard"],
                })

    return pruned_rows, unpruned_rows, billiard_rows


def compute_stats(rows, filter_group=None):
    """Compute per-facet-count summary statistics."""
    by_f = defaultdict(list)
    for r in rows:
        if filter_group and r.get("group") != filter_group:
            continue
        by_f[r["facets"]].append(r["time_ms"])

    stats = []
    prev_median = None
    for f in sorted(by_f.keys()):
        times = sorted(by_f[f])
        n = len(times)
        median = times[n // 2] if n % 2 == 1 else (times[n // 2 - 1] + times[n // 2]) / 2
        mean = sum(times) / n
        growth = median / prev_median if prev_median else None
        stats.append({
            "F": f,
            "N": n,
            "median_ms": median,
            "mean_ms": mean,
            "min_ms": min(times),
            "max_ms": max(times),
            "growth": growth,
        })
        prev_median = median
    return stats


def fit_model(stats):
    """Fit exponential model T(F) = a * b^F via log-linear regression."""
    F = np.array([s["F"] for s in stats])
    log_t = np.log(np.array([s["median_ms"] / 1000.0 for s in stats]))  # seconds

    # log(T) = log(a) + F * log(b)
    A = np.column_stack([np.ones_like(F), F])
    coeffs, residuals, _, _ = np.linalg.lstsq(A, log_t, rcond=None)
    log_a, log_b = coeffs
    a = np.exp(log_a)
    b = np.exp(log_b)

    # R^2
    predicted = log_a + F * log_b
    ss_res = np.sum((log_t - predicted) ** 2)
    ss_tot = np.sum((log_t - np.mean(log_t)) ** 2)
    r_squared = 1 - ss_res / ss_tot

    return a, b, r_squared


def update_timing_model(a, b, r_squared, stats):
    """Write updated timing model to JSON."""
    PROFILING_DIR.mkdir(parents=True, exist_ok=True)
    model = {
        "model": {
            "type": "exponential",
            "formula": "T(F) = a * b^F",
            "parameters": {"a": a, "b": b},
            "units": "seconds",
            "source": "benchmark.py (random polytopes from benchmark.jsonl)",
        },
        "fit_quality": {
            "r_squared": r_squared,
            "data_points": sum(s["N"] for s in stats),
            "facet_range": [stats[0]["F"], stats[-1]["F"]],
        },
    }
    MODEL_PATH.write_text(json.dumps(model, indent=2) + "\n")
    print(f"  Updated {MODEL_PATH}")


def plot_unified(pruned_rows, unpruned_rows, billiard_rows, pruned_stats_random, a_rand, b_rand, r2_rand):
    """Unified figure showing both polytope classes with fitted models."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    # Separate pruned by group
    pruned_random = [r for r in pruned_rows if r.get("group") == "random"]
    pruned_lag = [r for r in pruned_rows if r.get("group") == "lagrangian"]

    # Fit models for all datasets
    pruned_stats_lag = compute_stats(pruned_rows, filter_group="lagrangian")
    unpruned_stats = compute_stats(unpruned_rows)
    billiard_stats = compute_stats(billiard_rows)

    a_lag, b_lag, r2_lag = fit_model(pruned_stats_lag) if len(pruned_stats_lag) >= 2 else (None, None, None)
    a_unp, b_unp, r2_unp = fit_model(unpruned_stats) if len(unpruned_stats) >= 2 else (None, None, None)
    a_bil, b_bil, r2_bil = fit_model(billiard_stats) if len(billiard_stats) >= 2 else (None, None, None)

    fig, ax = plt.subplots(figsize=(TEXT_WIDTH, 4.0))

    # HK2017 pruned (random polytopes)
    F_p_rand = [r["facets"] for r in pruned_random]
    T_p_rand = [r["time_ms"] / 1000.0 for r in pruned_random]
    ax.scatter(F_p_rand, T_p_rand, alpha=0.3, s=15, color="steelblue", marker="o",
               label="HK2017 pruned (random)")

    # HK2017 pruned (Lagrangian products)
    F_p_lag = [r["facets"] for r in pruned_lag]
    T_p_lag = [r["time_ms"] / 1000.0 for r in pruned_lag]
    ax.scatter(F_p_lag, T_p_lag, alpha=0.5, s=25, color="darkblue", marker="s",
               label="HK2017 pruned (Lagrangian)")

    # HK2017 unpruned (random polytopes, F≤7)
    if unpruned_rows:
        F_u = [r["facets"] for r in unpruned_rows]
        T_u = [r["time_ms"] / 1000.0 for r in unpruned_rows]
        ax.scatter(F_u, T_u, alpha=0.5, s=20, color="orange", marker="^",
                   label="HK2017 unpruned (random)")

    # Billiard (Lagrangian products)
    if billiard_rows:
        F_b = [r["facets"] for r in billiard_rows]
        T_b = [r["time_ms"] / 1000.0 for r in billiard_rows]
        ax.scatter(F_b, T_b, alpha=0.6, s=30, color="green", marker="s",
                   label="Billiard (Lagrangian)")

    # Fitted models
    F_fit_wide = np.linspace(5, 16, 100)
    F_fit_narrow = np.linspace(5, 10, 100)

    # Pruned (random): extrapolate to F=16
    T_fit_rand = a_rand * b_rand ** F_fit_wide
    ax.plot(F_fit_wide, T_fit_rand, color="steelblue", linewidth=2, linestyle="--", alpha=0.7)

    # Pruned (Lagrangian)
    if a_lag is not None:
        T_fit_lag = a_lag * b_lag ** F_fit_narrow
        ax.plot(F_fit_narrow, T_fit_lag, color="darkblue", linewidth=2, linestyle="--", alpha=0.7)

    # Unpruned (random, F≤7)
    if a_unp is not None:
        F_fit_unp = np.linspace(5, 7, 50)
        T_fit_unp = a_unp * b_unp ** F_fit_unp
        ax.plot(F_fit_unp, T_fit_unp, color="orange", linewidth=2, linestyle="--", alpha=0.7)

    # Billiard (Lagrangian)
    if a_bil is not None:
        T_fit_bil = a_bil * b_bil ** F_fit_narrow
        ax.plot(F_fit_narrow, T_fit_bil, color="green", linewidth=2, linestyle="--", alpha=0.7)

    # Crosspolytope reference at F=16 (random polytope model only)
    T_crosspolytope = a_rand * b_rand ** 16
    ax.axvline(16, color="gray", linestyle=":", alpha=0.5)
    ax.scatter([16], [T_crosspolytope], s=120, color="red", marker="*",
               zorder=6, edgecolors="black", linewidths=1.5)
    ax.annotate(
        "Crosspolytope (F=16)", xy=(16, T_crosspolytope),
        xytext=(-60, -25), textcoords="offset points",
        fontsize=8, ha="right", va="top",
        arrowprops=dict(arrowstyle="->", color="gray", lw=0.8),
    )

    ax.set_yscale("log")
    ax.set_xlabel("Facet count $F$")
    ax.set_ylabel("Computation time (seconds)")
    ax.set_title("EHZ capacity benchmarks")
    ax.legend(loc="upper left", fontsize=8)
    ax.grid(True, alpha=0.3, which="both")
    ax.set_xlim(4.5, 17)
    fig.tight_layout()

    out = FIGURES_DIR / "benchmark_timing.png"
    fig.savefig(out)
    plt.close(fig)
    print(f"  {out.name}: {len(pruned_random)} pruned (random), {len(pruned_lag)} pruned (Lagrangian), {len(unpruned_rows)} unpruned, {len(billiard_rows)} billiard")

    # Print all fit parameters
    if a_lag:
        print(f"  Pruned (Lagrangian): T(F) = {a_lag:.2e} * {b_lag:.2f}^F (R^2 = {r2_lag:.3f})")
    if a_unp:
        print(f"  Unpruned (random): T(F) = {a_unp:.2e} * {b_unp:.2f}^F (R^2 = {r2_unp:.3f})")
    if a_bil:
        print(f"  Billiard (Lagrangian): T(F) = {a_bil:.2e} * {b_bil:.2f}^F (R^2 = {r2_bil:.3f})")


def print_summary(pruned_stats, unpruned_stats, billiard_stats, a, b, r_squared):
    """Print summary table and model to stdout."""
    print("\n=== HK2017 Pruned Timing Model (Random Polytopes) ===")
    print(f"T(F) = {a:.2e} * {b:.2f}^F seconds (R^2 = {r_squared:.3f})")
    print(f"Growth rate: {b:.2f}x per facet")
    print()
    print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10} {'Min':>10} {'Max':>10} {'Growth':>7}")
    for s in pruned_stats:
        g = f"{s['growth']:.1f}x" if s["growth"] else "-"
        print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f} "
              f"{s['min_ms']:>10.1f} {s['max_ms']:>10.1f} {g:>7}")

    if unpruned_stats:
        print("\n=== HK2017 Unpruned (F≤7) ===")
        print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10}")
        for s in unpruned_stats:
            print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f}")

    if billiard_stats:
        print("\n=== Billiard (Lagrangian Products) ===")
        print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10}")
        for s in billiard_stats:
            print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f}")

    # Extrapolation to F=16
    T_16 = a * b ** 16
    print(f"\n=== Extrapolation to Crosspolytope (F=16) ===")
    print(f"Predicted time: {T_16:.2f} seconds ({T_16/60:.1f} minutes)")


def main():
    if not DATA_PATH.exists():
        print(f"Dataset not found: {DATA_PATH}", file=__import__("sys").stderr)
        print("Run: cd crates && cargo run --bin benchmark --release", file=__import__("sys").stderr)
        __import__("sys").exit(1)

    pruned_rows, unpruned_rows, billiard_rows = load_dataset()
    print(f"Loaded {len(pruned_rows)} pruned, {len(unpruned_rows)} unpruned, {len(billiard_rows)} billiard from {DATA_PATH}")

    # Fit model on random polytopes only
    pruned_stats = compute_stats(pruned_rows, filter_group="random")
    unpruned_stats = compute_stats(unpruned_rows)
    billiard_stats = compute_stats(billiard_rows)

    a, b, r_squared = fit_model(pruned_stats)

    print_summary(pruned_stats, unpruned_stats, billiard_stats, a, b, r_squared)
    update_timing_model(a, b, r_squared, pruned_stats)
    plot_unified(pruned_rows, unpruned_rows, billiard_rows, pruned_stats, a, b, r_squared)

    print("\nDone.")


if __name__ == "__main__":
    main()
