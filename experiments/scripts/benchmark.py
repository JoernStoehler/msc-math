#!/usr/bin/env python3
"""
Benchmark EHZ capacity computation across facet counts.

Goal: Derive timing model T(F) = a * b^F from benchmark dataset,
      produce separate figures for random polytopes vs Lagrangian products.
Input: experiments/data/benchmark.jsonl (generated by benchmark.rs)
Output: experiments/profiling/timing_model.json (updated model),
        experiments/figures/benchmark_timing_random.png (random polytopes),
        experiments/figures/benchmark_timing_lagrangian.png (Lagrangian products)
"""

import json
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
PROFILING_DIR = REPO_ROOT / "experiments" / "profiling"
FIGURES_DIR = REPO_ROOT / "experiments" / "figures"
DATA_PATH = REPO_ROOT / "experiments" / "data" / "benchmark.jsonl"

MODEL_PATH = PROFILING_DIR / "timing_model.json"


def load_dataset():
    """Load benchmark dataset JSONL with all three algorithms."""
    pruned_rows = []
    unpruned_rows = []
    billiard_rows = []

    with open(DATA_PATH) as f:
        for line in f:
            row = json.loads(line)

            # Pruned (all polytopes)
            pruned_rows.append({
                "facets": row["facet_count"],
                "time_ms": row["time_pruned_ms"],
                "capacity": row["capacity_pruned"],
                "iterations": row["iterations_pruned"],
                "group": row["group"],
            })

            # Unpruned (F≤7 only, random polytopes only)
            if row["time_unpruned_ms"] is not None:
                unpruned_rows.append({
                    "facets": row["facet_count"],
                    "time_ms": row["time_unpruned_ms"],
                    "capacity": row["capacity_unpruned"],
                    "iterations": row["iterations_unpruned"],
                })

            # Billiard (Lagrangian products only)
            if row["time_billiard_ms"] is not None:
                billiard_rows.append({
                    "facets": row["facet_count"],
                    "time_ms": row["time_billiard_ms"],
                    "capacity": row["capacity_billiard"],
                    "iterations": row["iterations_billiard"],
                })

    return pruned_rows, unpruned_rows, billiard_rows


def compute_stats(rows, filter_group=None):
    """Compute per-facet-count summary statistics."""
    by_f = defaultdict(list)
    for r in rows:
        if filter_group and r.get("group") != filter_group:
            continue
        by_f[r["facets"]].append(r["time_ms"])

    stats = []
    prev_median = None
    for f in sorted(by_f.keys()):
        times = sorted(by_f[f])
        n = len(times)
        median = times[n // 2] if n % 2 == 1 else (times[n // 2 - 1] + times[n // 2]) / 2
        mean = sum(times) / n
        growth = median / prev_median if prev_median else None
        stats.append({
            "F": f,
            "N": n,
            "median_ms": median,
            "mean_ms": mean,
            "min_ms": min(times),
            "max_ms": max(times),
            "growth": growth,
        })
        prev_median = median
    return stats


def fit_model(stats):
    """Fit exponential model T(F) = a * b^F via log-linear regression."""
    F = np.array([s["F"] for s in stats])
    log_t = np.log(np.array([s["median_ms"] / 1000.0 for s in stats]))  # seconds

    # log(T) = log(a) + F * log(b)
    A = np.column_stack([np.ones_like(F), F])
    coeffs, residuals, _, _ = np.linalg.lstsq(A, log_t, rcond=None)
    log_a, log_b = coeffs
    a = np.exp(log_a)
    b = np.exp(log_b)

    # R^2
    predicted = log_a + F * log_b
    ss_res = np.sum((log_t - predicted) ** 2)
    ss_tot = np.sum((log_t - np.mean(log_t)) ** 2)
    r_squared = 1 - ss_res / ss_tot

    return a, b, r_squared


def update_timing_model(a, b, r_squared, stats):
    """Write updated timing model to JSON."""
    PROFILING_DIR.mkdir(parents=True, exist_ok=True)
    model = {
        "model": {
            "type": "exponential",
            "formula": "T(F) = a * b^F",
            "parameters": {"a": a, "b": b},
            "units": "seconds",
            "source": "benchmark.py (random polytopes from benchmark.jsonl)",
        },
        "fit_quality": {
            "r_squared": r_squared,
            "data_points": sum(s["N"] for s in stats),
            "facet_range": [stats[0]["F"], stats[-1]["F"]],
        },
    }
    MODEL_PATH.write_text(json.dumps(model, indent=2) + "\n")
    print(f"  Updated {MODEL_PATH}")


def plot_random_polytopes(pruned_rows, unpruned_rows, pruned_stats, a, b, r_squared):
    """Plot HK2017 pruned + unpruned on random polytopes, extrapolate to F=16."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    # Filter pruned to random only
    pruned_random = [r for r in pruned_rows if r.get("group") == "random"]

    fig, ax = plt.subplots(figsize=(10, 6))

    # Scatter: HK2017 pruned (random)
    F_pruned = [r["facets"] for r in pruned_random]
    T_pruned = [r["time_ms"] / 1000.0 for r in pruned_random]
    ax.scatter(F_pruned, T_pruned, alpha=0.3, s=15, color="steelblue", label="HK2017 pruned")

    # Scatter: HK2017 unpruned (F≤7)
    if unpruned_rows:
        F_unpruned = [r["facets"] for r in unpruned_rows]
        T_unpruned = [r["time_ms"] / 1000.0 for r in unpruned_rows]
        ax.scatter(F_unpruned, T_unpruned, alpha=0.5, s=20, color="orange", marker="^", label="HK2017 unpruned")

    # Medians: HK2017 pruned
    F_med = [s["F"] for s in pruned_stats]
    T_med = [s["median_ms"] / 1000.0 for s in pruned_stats]
    ax.scatter(F_med, T_med, s=80, color="darkblue", zorder=5, marker="D", edgecolors="black", linewidths=1.5,
               label="Median (pruned)")

    # Fitted model: extrapolate to F=16
    F_fit = np.linspace(5, 16, 100)
    T_fit = a * b ** F_fit
    ax.plot(F_fit, T_fit, color="red", linewidth=2, linestyle="--",
            label=f"Fitted: $T(F) = {a:.2e} \\cdot {b:.2f}^F$ ($R^2 = {r_squared:.3f}$)")

    # Crosspolytope reference at F=16
    T_crosspolytope = a * b ** 16
    ax.axvline(16, color="gray", linestyle=":", alpha=0.5)
    ax.scatter([16], [T_crosspolytope], s=120, color="red", marker="*", zorder=6, edgecolors="black", linewidths=1.5)
    ax.text(16.2, T_crosspolytope, "Crosspolytope\n(F=16)", fontsize=9, va="center")

    ax.set_yscale("log")
    ax.set_xlabel("Facet count $F$", fontsize=11)
    ax.set_ylabel("Computation time (seconds)", fontsize=11)
    ax.set_title("HK2017 on random polytopes: pruned vs unpruned", fontsize=12)
    ax.legend(loc="upper left", fontsize=9)
    ax.grid(True, alpha=0.3, which="both")
    ax.set_xlim(4.5, 16.5)
    fig.tight_layout()

    out = FIGURES_DIR / "benchmark_timing_random.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    print(f"  {out.name}: {len(pruned_random)} pruned, {len(unpruned_rows)} unpruned")


def plot_lagrangian_products(pruned_rows, billiard_rows):
    """Plot HK2017 pruned vs billiard on Lagrangian products."""
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    # Filter pruned to Lagrangian only
    pruned_lag = [r for r in pruned_rows if r.get("group") == "lagrangian"]

    fig, ax = plt.subplots(figsize=(10, 6))

    # Scatter: HK2017 pruned (Lagrangian)
    F_pruned = [r["facets"] for r in pruned_lag]
    T_pruned = [r["time_ms"] / 1000.0 for r in pruned_lag]
    ax.scatter(F_pruned, T_pruned, alpha=0.5, s=30, color="steelblue", marker="o", label="HK2017 pruned")

    # Scatter: Billiard
    F_billiard = [r["facets"] for r in billiard_rows]
    T_billiard = [r["time_ms"] / 1000.0 for r in billiard_rows]
    ax.scatter(F_billiard, T_billiard, alpha=0.5, s=30, color="green", marker="s", label="Billiard")

    # Medians
    pruned_stats_lag = compute_stats(pruned_rows, filter_group="lagrangian")
    billiard_stats = compute_stats(billiard_rows)

    F_med_pruned = [s["F"] for s in pruned_stats_lag]
    T_med_pruned = [s["median_ms"] / 1000.0 for s in pruned_stats_lag]
    ax.scatter(F_med_pruned, T_med_pruned, s=80, color="darkblue", zorder=5, marker="D",
               edgecolors="black", linewidths=1.5, label="Median (pruned)")

    F_med_billiard = [s["F"] for s in billiard_stats]
    T_med_billiard = [s["median_ms"] / 1000.0 for s in billiard_stats]
    ax.scatter(F_med_billiard, T_med_billiard, s=80, color="darkgreen", zorder=5, marker="s",
               edgecolors="black", linewidths=1.5, label="Median (billiard)")

    ax.set_yscale("log")
    ax.set_xlabel("Facet count $F$", fontsize=11)
    ax.set_ylabel("Computation time (seconds)", fontsize=11)
    ax.set_title("HK2017 vs Billiard on random Lagrangian products", fontsize=12)
    ax.legend(loc="upper left", fontsize=9)
    ax.grid(True, alpha=0.3, which="both")
    ax.set_xlim(5.5, 10.5)
    fig.tight_layout()

    out = FIGURES_DIR / "benchmark_timing_lagrangian.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    print(f"  {out.name}: {len(pruned_lag)} pruned, {len(billiard_rows)} billiard")


def print_summary(pruned_stats, unpruned_stats, billiard_stats, a, b, r_squared):
    """Print summary table and model to stdout."""
    print("\n=== HK2017 Pruned Timing Model (Random Polytopes) ===")
    print(f"T(F) = {a:.2e} * {b:.2f}^F seconds (R^2 = {r_squared:.3f})")
    print(f"Growth rate: {b:.2f}x per facet")
    print()
    print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10} {'Min':>10} {'Max':>10} {'Growth':>7}")
    for s in pruned_stats:
        g = f"{s['growth']:.1f}x" if s["growth"] else "-"
        print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f} "
              f"{s['min_ms']:>10.1f} {s['max_ms']:>10.1f} {g:>7}")

    if unpruned_stats:
        print("\n=== HK2017 Unpruned (F≤7) ===")
        print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10}")
        for s in unpruned_stats:
            print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f}")

    if billiard_stats:
        print("\n=== Billiard (Lagrangian Products) ===")
        print(f"{'F':>3} {'N':>3} {'Median':>10} {'Mean':>10}")
        for s in billiard_stats:
            print(f"{s['F']:>3} {s['N']:>3} {s['median_ms']:>10.1f} {s['mean_ms']:>10.1f}")

    # Extrapolation to F=16
    T_16 = a * b ** 16
    print(f"\n=== Extrapolation to Crosspolytope (F=16) ===")
    print(f"Predicted time: {T_16:.2f} seconds ({T_16/60:.1f} minutes)")


def main():
    if not DATA_PATH.exists():
        print(f"Dataset not found: {DATA_PATH}", file=__import__("sys").stderr)
        print("Run: cd crates && cargo run --bin benchmark --release", file=__import__("sys").stderr)
        __import__("sys").exit(1)

    pruned_rows, unpruned_rows, billiard_rows = load_dataset()
    print(f"Loaded {len(pruned_rows)} pruned, {len(unpruned_rows)} unpruned, {len(billiard_rows)} billiard from {DATA_PATH}")

    # Fit model on random polytopes only
    pruned_stats = compute_stats(pruned_rows, filter_group="random")
    unpruned_stats = compute_stats(unpruned_rows)
    billiard_stats = compute_stats(billiard_rows)

    a, b, r_squared = fit_model(pruned_stats)

    print_summary(pruned_stats, unpruned_stats, billiard_stats, a, b, r_squared)
    update_timing_model(a, b, r_squared, pruned_stats)

    # Generate two separate figures
    plot_random_polytopes(pruned_rows, unpruned_rows, pruned_stats, a, b, r_squared)
    plot_lagrangian_products(pruned_rows, billiard_rows)

    print("\nDone.")


if __name__ == "__main__":
    main()
