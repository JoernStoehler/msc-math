"""Independent exact audit: exterior determinants and perfect matchings.
No imports from the author's implementation; Python standard library only.
"""
from itertools import combinations, permutations
from collections import Counter
from fractions import Fraction

pairs=list(combinations(range(6),2)); ix={p:i for i,p in enumerate(pairs)}
e=[[int(i==j) for i in range(6)] for j in range(6)]+[[0]*6]
def sub(a,b):return [x-y for x,y in zip(a,b)]
def wedge(a,b):return tuple(a[i]*b[j]-a[j]*b[i] for i,j in pairs)
def det(cols):
    a=[[Fraction(cols[j][i]) for j in range(6)] for i in range(6)]
    z=Fraction(1)
    for k in range(6):
        r=next((r for r in range(k,6) if a[r][k]),None)
        if r is None:return 0
        if r!=k:a[r],a[k]=a[k],a[r];z=-z
        v=a[k][k];z*=v
        for r in range(k+1,6):
            m=a[r][k]/v
            for j in range(k+1,6):a[r][j]-=m*a[k][j]
    assert z.denominator==1
    return int(z)
T=list(combinations(range(7),3))
cols=[(sub(e[i],e[k]),sub(e[j],e[k])) for i,j,k in T]
V=[wedge(a,b) for a,b in cols]
coeff={}
for inds in combinations(range(35),3):
    coeff[inds]=det([c for i in inds for c in cols[i]])
    if any(len(set(T[i])&set(T[j]))>=2 for i,j in combinations(inds,2)):
        assert coeff[inds]==0
assert set(coeff.values())=={-1,0,1}
print('determinant coefficient histogram',dict(Counter(coeff.values())))
adj=[{j for j in range(35) if j!=i and len(set(T[i])&set(T[j]))<=1} for i in range(35)]
maximal=[]
def extend(cur,candidates):
    if not candidates:
        if not any(all(j in adj[i] for i in cur) for j in range(35) if j not in cur):maximal.append(cur)
        return
    for j in sorted(candidates):extend(cur+(j,),{k for k in candidates if k>j and k in adj[j]})
extend((),set(range(35)))
assert Counter(map(len,maximal))=={5:420,7:30}
print('independent increasing-index clique recursion',dict(Counter(map(len,maximal))))
for c in maximal:
    edges=[x for x in combinations(c,3) if coeff[x]]
    assert len(edges)==(4 if len(c)==5 else 7)
    if len(c)==5:
        deg=Counter(i for x in edges for i in x)
        assert sorted(deg.values())==[2,2,2,3,3]
        central={i for i in c if deg[i]==3};outer=set(c)-central
        assert set(edges)=={tuple(sorted(central|{i})) for i in outer}|{tuple(sorted(outer))}

# Perfect matching expansion independent of recursive Pfaffian evaluator.
matchings=[]
def match(cur,left):
    if not left:
        flat=[i for p in cur for i in p]
        inversions=sum(flat[i]>flat[j] for i in range(6) for j in range(i+1,6))
        matchings.append(((-1)**inversions,cur));return
    i=left[0]
    for j in left[1:]:match(cur+((i,j),),[k for k in left if k not in (i,j)])
match((),list(range(6)))
assert len(matchings)==15
def pf(v):
    z=0
    for sign,ps in matchings:
        term=sign
        for p in ps:term*=v[ix[p]]
        z+=term
    return z
def add(*vs):return tuple(sum(v[k] for v in vs) for k in range(15))
# Every determinant polarization agrees with independently built Pf polynomial.
for inds,c in coeff.items():assert pf(add(*(V[i] for i in inds)))==c
F=[0]*15;p=[0]*15
for i in range(3):
    for j in range(3):
        F[ix[i,j+3]]=1 if i==j else -1
        p[ix[i,j+3]]=0 if i==j else -1
signed=[tuple(s*x for x in v) for v in V for s in (1,-1)]
active=[v for v in signed if sum(a*b for a,b in zip(v,p))==1]
assert len(active)==18 and pf(F)==4
for v in active:
    assert pf(add(F,v))-pf(add(F,tuple(-x for x in v)))==4
# B_ij equals coefficient with one A and two rank-two forms.
B=[[0]*18 for _ in range(18)]
for i,j in combinations(range(18),2):
    B[i][j]=B[j][i]=pf(add(F,active[i],active[j]))-pf(add(F,active[i]))-pf(add(F,active[j]))+pf(F)
assert set(v for row in B for v in row)=={0,1,2}
components=[];remaining=set(range(18))
while remaining:
    i=min(remaining);c={i};front={i}
    while front:
        new={j for i in front for j in range(18) if B[i][j]==2}-c;c|=new;front=new
    assert len(c)==3
    center=next(i for i in c if sum(B[i][j]==2 for j in c)==2)
    s={i:1 if i==center else -1 for i in c}
    assert all(1-B[i][j]==s[i]*s[j] for i in c for j in c)
    components.append(c);remaining-=c
assert len(components)==6
assert all(B[i][j]<=1 for c in components for i in c for j in set(range(18))-c)
print('pyramid perfect-matchings check',dict(Counter(v for row in B for v in row)),'six rank-one within-path squares')

# Four equality sign choices are generated by explicit coordinate permutations.
t=lambda i,j,k:V[T.index(tuple(sorted((i-1,j-1,k-1))))]
gens=[t(1,3,5),tuple(-x for x in t(2,4,6)),t(1,2,7),t(3,4,7),t(5,6,7)]
def permute(v,perm):
    out=[0]*15
    for (i,j),x in zip(pairs,v):
        a,b=perm[i],perm[j]
        out[ix[min(a,b),max(a,b)]]+=(1 if a<b else -1)*x
    return tuple(out)
P=(2,3,0,1,4,5);N=(1,0,3,2,5,4)
assert permute(gens[0],P)==tuple(-x for x in gens[0])
assert permute(gens[1],P)==tuple(-x for x in gens[1])
assert set(permute(v,P) for v in gens[2:])==set(gens[2:])
assert set(permute(v,N) for v in gens[:2])==set(tuple(-x for x in v) for v in gens[:2])
assert set(permute(v,N) for v in gens[2:])==set(tuple(-x for x in v) for v in gens[2:])
print('four signed F32 equality patterns are relabelings: PASS')
