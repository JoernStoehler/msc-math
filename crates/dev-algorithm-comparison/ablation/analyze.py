def plot_timing(entries):
    """Timing comparison figure: all variants per group and F."""
    groups_to_plot = ["random_generic", "random_lagrangian"]
    group_display = {
        "random_generic": "Random generic polytopes",
        "random_lagrangian": "Random Lagrangian products",
    }

    fig, axes = plt.subplots(1, 2, figsize=(TEXT_WIDTH, 3.5), sharey=False)

    colors = {
        "a0_unpruned": "#e08020",
        "a1_vertex_adj": "#2060c0",
        "a2_omega_directed": "#20a040",
        "a3_reeb_feasible": "#a02080",
    }
    markers = {
        "a0_unpruned": "^",
        "a1_vertex_adj": "o",
        "a2_omega_directed": "s",
        "a3_reeb_feasible": "D",
    }

    for ax, group in zip(axes, groups_to_plot):
        group_entries = [e for e in entries if e["group"] == group]

        by_variant_f = defaultdict(lambda: defaultdict(list))
        for e in group_entries:
            by_variant_f[e["variant"]][e["facet_count"]].append(e["time_ms"])

        for variant in VARIANTS:
            f_vals = sorted(by_variant_f[variant].keys())
            if not f_vals:
                continue

            means = [float(np.mean(by_variant_f[variant][f])) for f in f_vals]
            stds = [float(np.std(by_variant_f[variant][f], ddof=1)) for f in f_vals]

            ax.errorbar(
                f_vals,
                means,
                yerr=stds,
                marker=markers[variant],
                color=colors[variant],
                linewidth=2,
                markersize=6,
                capsize=4,
                capthick=1.5,
                elinewidth=1.5,
                alpha=0.9,
                label=f"{VARIANT_LABELS[variant]}",
            )

        ax.set_yscale("log")
        ax.set_xlabel("Facet count $F$")
        ax.set_ylabel("Time (ms)")
        ax.set_title(group_display[group])
        ax.grid(True, alpha=0.3, which="both")
        # Integer x-ticks for facet count
        all_f = sorted(set(
            e["facet_count"] for e in entries if e["group"] == group
        ))
        ax.set_xticks(all_f)

    fig.suptitle(
        "Adjacency pruning: timing by facet count (mean $\\pm$ std, $n=5$)",
    )
    # Shared legend from first axis (both panels have same entries)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=4, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=[0, 0.08, 1, 0.95])
    fig.savefig(FIGURE_PATH)
    plt.close(fig)
    print(f"Figure: {FIGURE_PATH}")


# ============================================================================
# Main
# ============================================================================

def main():
    entries = load_dataset()
    n_total = len(entries)
    n_polytopes = len(set(e["polytope_name"] for e in entries))
    n_variants = len(set(e["variant"] for e in entries))
    print(f"Loaded {n_total} entries ({n_polytopes} polytopes x {n_variants} variants)")
    print(f"Groups: {sorted(set(e['group'] for e in entries))}")

    print_regression_table(entries)
    n_disagree = print_agreement_table(entries)
    print_timing_table(entries)
    print_iteration_table(entries)
    print_nonsimple_table(entries)
    fit_scaling_exponent(entries)
    plot_timing(entries)

    if n_disagree > 0:
        print(f"\nFAILURE: {n_disagree} disagreements found.", file=sys.stderr)
        sys.exit(1)
    else:
        print("\nAll variants agree. Ablation study complete.")


if __name__ == "__main__":
    main()
