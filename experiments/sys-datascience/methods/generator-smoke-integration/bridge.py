#!/usr/bin/env python3
"""Prepare opt-in sidecars from named alternative-generator smoke JSONL files.

This is intentionally independent of the retained producer/prepare binaries.
It validates the small smoke contract, preserves source identity and target
censoring, and never writes ``polytope-table.jsonl``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import sys
from typing import Any, Iterable


SCHEMA = "alternative-generator-smoke-row-v2"
PROVENANCE_SCHEMA = "generator-smoke-provenance-v1"
PREPARED_SCHEMA = "generator-smoke-prepared-v1"

# These are the values generated by the reviewed alternative smoke.  Unknown
# non-target fields are retained under ``geometry`` rather than discarded.
TARGET_FIELDS = {"sys", "capacity", "iterations", "target_ms"}
REQUIRED_FIELDS = {
    "schema",
    "sample_id",
    "law",
    "law_version",
    "seed",
    "row_index",
    "attempt",
    "attempts",
    "rejections",
    "parameter",
    "pair_bucket",
    "facet_count",
    "accepted",
    "validation_status",
}
NUMERIC_FIELDS = {
    "seed",
    "row_index",
    "attempt",
    "attempts",
    "rejections",
    "facet_count",
    "factor_q_area",
    "factor_p_area",
    "factor_q_support_cv",
    "factor_p_support_cv",
    "factor_q_gap_cv",
    "factor_p_gap_cv",
    "factor_q_isoperimetric_ratio",
    "factor_p_isoperimetric_ratio",
    "volume",
    "capacity",
    "sys",
    "iterations",
    "generation_ms",
    "validation_ms",
    "target_ms",
}
INTEGER_FIELDS = {"seed", "row_index", "attempt", "attempts", "rejections", "facet_count", "iterations"}
REQUIRED_INTEGER_FIELDS = {"seed", "row_index", "attempt", "attempts", "rejections", "facet_count"}
EXPECTED_GEOMETRY_FIELDS = {
    "factor_q_area",
    "factor_p_area",
    "factor_q_support_cv",
    "factor_p_support_cv",
    "factor_q_gap_cv",
    "factor_p_gap_cv",
    "factor_q_isoperimetric_ratio",
    "factor_p_isoperimetric_ratio",
    "volume",
}
SAMPLE_ID_RE = re.compile(
    r"^altgen-v2/(?P<law>[^/]+)/param=(?P<parameter>[^/]+)/"
    r"seed=(?P<seed>[0-9]+)/row=(?P<row_index>[0-9]+)/"
    r"(?:(?:attempt=(?P<attempt>[0-9]+))|(?P<exhausted>outcome=exhausted))/"
    r"(?P<pair_bucket>[0-9]+x[0-9]+)$"
)
PAIR_BUCKET_RE = re.compile(r"^(?P<q>[1-9][0-9]*)x(?P<p>[1-9][0-9]*)$")


class BridgeError(ValueError):
    """An input violates the opt-in smoke bridge contract."""


def _reject_constant(value: str) -> None:
    raise BridgeError(f"malformed numeric value {value!r}: non-finite JSON number")


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    try:
        handle = path.open("r", encoding="utf-8")
    except OSError as exc:
        raise BridgeError(f"cannot open {path}: {exc}") from exc
    with handle:
        for line_number, line in enumerate(handle, 1):
            if not line.strip():
                continue
            try:
                value = json.loads(line, parse_constant=_reject_constant)
            except (json.JSONDecodeError, BridgeError) as exc:
                raise BridgeError(f"{path}:{line_number}: malformed JSON: {exc}") from exc
            if not isinstance(value, dict):
                raise BridgeError(f"{path}:{line_number}: row must be an object")
            rows.append(value)
    return rows


def _finite_number(value: Any, field: str, source: str) -> None:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise BridgeError(f"{source}: field {field!r} must be numeric or null")
    if not math.isfinite(float(value)):
        raise BridgeError(f"{source}: field {field!r} is non-finite")


def _validate_nested_numbers(value: Any, field: str, source: str) -> None:
    """Reject overflowed JSON numbers even when an extension field is unknown."""
    if isinstance(value, float) and not math.isfinite(value):
        raise BridgeError(f"{source}: field {field!r} is non-finite")
    if isinstance(value, dict):
        for key, nested in value.items():
            _validate_nested_numbers(nested, f"{field}.{key}", source)
    elif isinstance(value, list):
        for index, nested in enumerate(value):
            _validate_nested_numbers(nested, f"{field}[{index}]", source)


def _canonical_identity(row: dict[str, Any], location: str) -> re.Match[str]:
    match = SAMPLE_ID_RE.fullmatch(row["sample_id"])
    if match is None:
        raise BridgeError(f"{location}: sample_id is not a canonical alternative-generator ID")
    groups = match.groupdict()
    for field in ("law", "parameter", "pair_bucket"):
        if groups[field] != row[field]:
            raise BridgeError(
                f"{location}: sample_id {row['sample_id']!r} disagrees with {field}={row[field]!r}"
            )
    for field in ("seed", "row_index"):
        if int(groups[field]) != row[field]:
            raise BridgeError(
                f"{location}: sample_id {row['sample_id']!r} disagrees with {field}={row[field]}"
            )
    attempt_token = groups["attempt"]
    if row["accepted"]:
        if attempt_token is None or int(attempt_token) != row["attempt"]:
            raise BridgeError(f"{location}: accepted sample_id must encode its attempt")
    else:
        if groups["exhausted"] is None:
            raise BridgeError(f"{location}: rejected sample_id must encode outcome=exhausted")
        if row["attempts"] != row["attempt"] + 1 or row["rejections"] != row["attempts"]:
            raise BridgeError(f"{location}: exhausted row must have attempts=rejections=attempt+1")
    return match


def _validate_geometry_and_target(row: dict[str, Any], location: str) -> None:
    geometry_values = [row.get(field) for field in EXPECTED_GEOMETRY_FIELDS]
    if row["accepted"] and any(value is None for value in geometry_values):
        raise BridgeError(f"{location}: accepted geometry must provide every expected geometry field")
    if not row["accepted"] and any(value is not None for value in geometry_values):
        raise BridgeError(f"{location}: rejected geometry must be null for every expected geometry field")

    target_values = {field: row.get(field) for field in TARGET_FIELDS}
    nonnull_target = [field for field, value in target_values.items() if value is not None]
    # The smoke producer writes target_ms=0.0 as a non-evaluated sentinel when
    # the target backend is disabled or facet-capped. It is normalized to null
    # in the prepared sidecar; any other partial target quartet is malformed.
    sentinel_only = nonnull_target == ["target_ms"] and target_values["target_ms"] == 0.0
    evaluated = all(target_values[field] is not None for field in TARGET_FIELDS)
    if evaluated:
        if row["validation_status"] != "survived":
            raise BridgeError(f"{location}: evaluated target quartet requires validation_status=survived")
        volume = row.get("volume")
        if volume is None or volume <= 0:
            raise BridgeError(f"{location}: evaluated target requires positive volume")
        if row["capacity"] <= 0:
            raise BridgeError(f"{location}: evaluated capacity must be positive")
        if row["sys"] < 0:
            raise BridgeError(f"{location}: evaluated sys must be non-negative")
        if row["iterations"] <= 0:
            raise BridgeError(f"{location}: evaluated iterations must be positive")
        if row["target_ms"] < 0:
            raise BridgeError(f"{location}: evaluated target_ms must be non-negative")
        expected_sys = row["capacity"] ** 2 / (2.0 * volume)
        if not math.isclose(row["sys"], expected_sys, rel_tol=1e-9, abs_tol=1e-12):
            raise BridgeError(f"{location}: sys disagrees with capacity^2/(2*volume)")
    elif nonnull_target and not sentinel_only:
        raise BridgeError(f"{location}: non-evaluated target fields must all be null (except target_ms=0 sentinel)")
    elif row["accepted"] and row["validation_status"] == "survived":
        reason = (row.get("rejection_reason") or "").lower()
        if "target backend disabled" not in reason:
            raise BridgeError(f"{location}: survived non-evaluated row must explain target omission")


def _validate_row(row: dict[str, Any], source: str, line_number: int) -> None:
    location = f"{source}:{line_number}"
    missing = sorted(REQUIRED_FIELDS - row.keys())
    if missing:
        raise BridgeError(f"{location}: missing required fields {', '.join(missing)}")
    if row["schema"] != SCHEMA:
        raise BridgeError(f"{location}: incompatible schema {row['schema']!r}; expected {SCHEMA!r}")
    for field, value in row.items():
        _validate_nested_numbers(value, field, location)
    for field in NUMERIC_FIELDS:
        if field in REQUIRED_INTEGER_FIELDS and row.get(field) is None:
            raise BridgeError(f"{location}: field {field!r} cannot be null")
        if field not in row or row[field] is None:
            continue
        _finite_number(row[field], field, location)
        if field in INTEGER_FIELDS and (isinstance(row[field], bool) or not isinstance(row[field], int)):
            raise BridgeError(f"{location}: field {field!r} must be an integer")
    for field in ("sample_id", "law", "law_version", "parameter", "pair_bucket", "validation_status"):
        if not isinstance(row[field], str) or not row[field]:
            raise BridgeError(f"{location}: field {field!r} must be a non-empty string")
    if not isinstance(row["accepted"], bool):
        raise BridgeError(f"{location}: field 'accepted' must be boolean")
    _canonical_identity(row, location)
    if row["attempt"] >= row["attempts"]:
        raise BridgeError(f"{location}: attempt must be less than attempts")
    # Accepted rows report the number of prior rejected attempts.  An
    # exhausted row has no accepted attempt and reports the full cap instead.
    if row["accepted"] and (row["attempts"] != row["attempt"] + 1 or row["rejections"] != row["attempt"]):
        raise BridgeError(f"{location}: accepted row must have attempts=attempt+1 and rejections=attempt")
    if not row["accepted"] and row["rejections"] < row["attempt"]:
        raise BridgeError(f"{location}: rejected row cannot report fewer rejections than attempt")
    if row["facet_count"] <= 0:
        raise BridgeError(f"{location}: facet_count must be positive")
    if row.get("pairing_id") is not None and not isinstance(row["pairing_id"], str):
        raise BridgeError(f"{location}: pairing_id must be a string or null")
    if row.get("rejection_reason") is not None and not isinstance(row["rejection_reason"], str):
        raise BridgeError(f"{location}: rejection_reason must be a string or null")
    bucket = PAIR_BUCKET_RE.fullmatch(row["pair_bucket"])
    if bucket is None:
        raise BridgeError(f"{location}: pair_bucket must have the form kxm with positive integers")
    if row["facet_count"] != int(bucket["q"]) + int(bucket["p"]):
        raise BridgeError(f"{location}: facet_count must equal the pair_bucket side-count sum")
    _validate_geometry_and_target(row, location)


def _target_status(row: dict[str, Any]) -> str:
    if not row["accepted"]:
        return "not_attempted_rejected"
    if row.get("sys") is not None and math.isfinite(float(row["sys"])):
        return "evaluated"
    reason = (row.get("rejection_reason") or "").lower()
    validation = str(row.get("validation_status", "")).lower()
    if validation == "runtime_cap" or "above predeclared facet-count cap" in reason:
        return "skipped_runtime_cap"
    if "target backend disabled" in reason:
        return "not_requested"
    if validation in {"target_failed", "target_error", "target_timeout"} or "target failed" in reason:
        return "failed"
    if row.get("sys") is None and row.get("capacity") is None:
        return "missing_target"
    return "target_unavailable"


def _identity_key(row: dict[str, Any]) -> tuple[Any, ...]:
    return (
        row["law_version"],
        row["law"],
        row["parameter"],
        row["seed"],
        row["row_index"],
        row["attempt"],
        row["pair_bucket"],
    )


def _source_fingerprint(path: Path) -> str:
    digest = hashlib.sha256()
    try:
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    except OSError as exc:
        raise BridgeError(f"cannot fingerprint {path}: {exc}") from exc
    return digest.hexdigest()


def _parse_inputs(values: Iterable[str]) -> list[tuple[str, Path]]:
    parsed: list[tuple[str, Path]] = []
    names: set[str] = set()
    for value in values:
        if "=" not in value:
            raise BridgeError(f"--input expects NAME=PATH, got {value!r}")
        name, raw_path = value.split("=", 1)
        if not name or not raw_path:
            raise BridgeError(f"--input expects non-empty NAME and PATH, got {value!r}")
        if name in names:
            raise BridgeError(f"duplicate input name {name!r}")
        names.add(name)
        parsed.append((name, Path(raw_path)))
    if not parsed:
        raise BridgeError("at least one --input NAME=PATH is required")
    return parsed


def build_sidecars(inputs: list[tuple[str, Path]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    provenance: list[dict[str, Any]] = []
    prepared: list[dict[str, Any]] = []
    seen_ids: dict[str, str] = {}
    seen_identity: dict[tuple[Any, ...], str] = {}
    pairing_identity: dict[str, tuple[Any, ...]] = {}
    schema_versions: set[str] = set()
    source_meta: list[dict[str, Any]] = []

    for source_name, path in inputs:
        rows = _read_jsonl(path)
        fingerprint = _source_fingerprint(path)
        source_meta.append({"name": source_name, "path": str(path), "sha256": fingerprint, "rows": len(rows)})
        for line_number, row in enumerate(rows, 1):
            _validate_row(row, source_name, line_number)
            schema_versions.add(str(row["schema"]))
            sample_id = row["sample_id"]
            if sample_id in seen_ids:
                raise BridgeError(f"duplicate sample_id {sample_id!r} in {source_name}; first seen in {seen_ids[sample_id]}")
            seen_ids[sample_id] = source_name
            identity = _identity_key(row)
            if identity in seen_identity:
                raise BridgeError(f"conflicting/repeated generator identity for sample_id {sample_id!r}; first seen as {seen_identity[identity]}")
            seen_identity[identity] = sample_id
            pairing_id = row.get("pairing_id")
            if pairing_id:
                pair_key = (row["law_version"], row["seed"], row["row_index"], row["attempt"], row["pair_bucket"])
                previous = pairing_identity.setdefault(pairing_id, pair_key)
                if previous != pair_key:
                    raise BridgeError(f"pairing_id {pairing_id!r} has conflicting identities")
            target_status = _target_status(row)
            target_evaluated = target_status == "evaluated"
            provenance_id = f"{source_name}:{sample_id}"
            geometry = {
                key: value
                for key, value in row.items()
                if key not in TARGET_FIELDS
                and key not in {"schema", "sample_id", "law", "law_version", "seed", "row_index", "attempt", "attempts", "rejections", "accepted", "validation_status", "rejection_reason", "pairing_id"}
            }
            missing_geometry = sorted(field for field in EXPECTED_GEOMETRY_FIELDS if geometry.get(field) is None)
            capability = {
                "target_free_geometry": row["accepted"] and bool(geometry),
                "factor_metrics": all(geometry.get(field) is not None for field in EXPECTED_GEOMETRY_FIELDS - {"volume"}),
                "volume": geometry.get("volume") is not None,
                "sys": target_evaluated,
                "full_exact_cache_payload": False,
                "standard_invariant_features": False,
            }
            provenance.append(
                {
                    "schema": PROVENANCE_SCHEMA,
                    "provenance_id": provenance_id,
                    "source_name": source_name,
                    "source_file": str(path),
                    "source_sha256": fingerprint,
                    "source_row": line_number,
                    "source_schema": row["schema"],
                    "law_version": row["law_version"],
                    "law": row["law"],
                    "parameter": row["parameter"],
                    "seed": row["seed"],
                    "sample_id": sample_id,
                    "row_index": row["row_index"],
                    "attempt": row["attempt"],
                    "attempts": row["attempts"],
                    "rejections": row["rejections"],
                    "pair_bucket": row["pair_bucket"],
                    "facet_count": row["facet_count"],
                    "pairing_id": pairing_id,
                    "accepted": row["accepted"],
                    "validation_status": row["validation_status"],
                    "rejection_reason": row.get("rejection_reason"),
                    "target_status": target_status,
                    "capabilities": capability,
                }
            )
            prepared.append(
                {
                    "schema": PREPARED_SCHEMA,
                    "join_key": sample_id,
                    "provenance_id": provenance_id,
                    "source_name": source_name,
                    "law_version": row["law_version"],
                    "law": row["law"],
                    "parameter": row["parameter"],
                    "seed": row["seed"],
                    "row_index": row["row_index"],
                    "attempt": row["attempt"],
                    "pair_bucket": row["pair_bucket"],
                    "facet_count": row["facet_count"],
                    "pairing_id": pairing_id,
                    "accepted": row["accepted"],
                    "validation_status": row["validation_status"],
                    "target_status": target_status,
                    "geometry": geometry,
                    "sys": row.get("sys") if target_evaluated else None,
                    "capacity": row.get("capacity") if target_evaluated else None,
                    "iterations": row.get("iterations") if target_evaluated else None,
                    "target_ms": row.get("target_ms") if target_evaluated else None,
                    "missing_geometry_fields": missing_geometry,
                    "censored_fields": ["sys", "capacity", "iterations", "target_ms"] if not target_evaluated else [],
                    "capabilities": capability,
                }
            )

    if schema_versions != {SCHEMA}:
        raise BridgeError(f"incompatible schema versions: {sorted(schema_versions)}")
    report = {
        "schema": "generator-smoke-integration-report-v1",
        "input_count": len(inputs),
        "source_files": source_meta,
        "row_count": len(prepared),
        "provenance_count": len(provenance),
        "prepared_count": len(prepared),
        "unique_sample_ids": len(seen_ids),
        "target_status_counts": _counts(prepared, "target_status"),
        "validation_status_counts": _counts(prepared, "validation_status"),
        "accepted_rows": sum(1 for row in prepared if row["accepted"]),
        "evaluated_sys_rows": sum(1 for row in prepared if row["target_status"] == "evaluated"),
        "blocked_standard_features": [
            "face_lattice_combinatorial_features",
            "two_face_symplectic_area_features",
            "exact_dual_vertex_volume_features",
            "cached_exact_capacity_features",
        ],
        "interpretation_boundary": "Named small generator smoke only; sidecar plumbing and target censoring, not retained-population or transfer evidence.",
    }
    return provenance, prepared, report


def _counts(rows: list[dict[str, Any]], field: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for row in rows:
        value = str(row[field])
        out[value] = out.get(value, 0) + 1
    return dict(sorted(out.items()))


def _write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, sort_keys=False, separators=(",", ":"), allow_nan=False))
            handle.write("\n")


def _write_json(path: Path, value: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(value, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", action="append", default=[], metavar="NAME=PATH", help="named smoke JSONL input; repeatable")
    parser.add_argument("--out-dir", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        inputs = _parse_inputs(args.input)
        provenance, prepared, report = build_sidecars(inputs)
        _write_jsonl(args.out_dir / "generator-smoke-provenance.jsonl", provenance)
        _write_jsonl(args.out_dir / "generator-smoke-prepared.jsonl", prepared)
        _write_json(args.out_dir / "integration-report.json", report)
    except BridgeError as exc:
        print(f"generator-smoke-integration: error: {exc}", file=sys.stderr)
        return 2
    print(f"wrote {len(prepared)} prepared rows and {len(provenance)} provenance rows to {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
